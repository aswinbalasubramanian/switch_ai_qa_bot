#!/usr/bin/env python3
"""Run the guardrail evals and write evals/report.md.

  python evals/run_evals.py            # exit 1 if any case fails
  python evals/run_evals.py --verbose  # also print every case

Each line of evals/cases.jsonl is one case:
  {"direction": "input"|"output", "text": "...", "expect": "allow"|"refuse", "category": "..."}
For refused inputs the category must match too (e.g. a prompt-injection case must be caught
as injection, not just refused for some other reason).
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "guardrails"))
import guard  # noqa: E402


def run(verbose=False):
    cases = [json.loads(l) for l in open(os.path.join(HERE, "cases.jsonl"), encoding="utf-8") if l.strip()]
    stats = collections.OrderedDict()
    failures = []
    for i, c in enumerate(cases, 1):
        if c["direction"] == "switch_prompt":
            # Full prompt as Switch sends it: control prompts and our own agents' handoffs pass,
            # people's messages are checked.
            sender, message = guard.parse_switch_prompt(c["text"])
            if message is None or sender in guard.OUR_AGENTS:
                v = {"allow": True, "category": "pass_through"}
            else:
                v = guard.check_input(message)
            got = "allow" if v["allow"] else "refuse"
            got_cat = v["category"]
            ok = got == c["expect"] and (c["expect"] == "allow" or got_cat == c["category"])
        elif c["direction"] == "input":
            v = guard.check_input(c["text"])
            got = "allow" if v["allow"] else "refuse"
            got_cat = v["category"]
            ok = got == c["expect"] and (c["expect"] == "allow" or got_cat == c["category"])
        else:
            v = guard.check_output(c["text"])
            got = "allow" if v["allow"] else "refuse"
            got_cat = ",".join(v["problems"]) or "clean"
            ok = got == c["expect"] and (c["expect"] == "allow" or c["category"] in v["problems"])
        key = (c["direction"], c["expect"], c["category"])
        s = stats.setdefault(key, [0, 0])
        s[0] += ok
        s[1] += 1
        if not ok:
            failures.append((i, c, got, got_cat))
        if verbose:
            print(("PASS " if ok else "FAIL ") + c["direction"] + " " + c["category"] + ": " + c["text"][:70].replace("\n", " "))

    total = sum(s[1] for s in stats.values())
    passed = sum(s[0] for s in stats.values())
    lines = ["# Guardrail eval report", "",
             f"**{passed}/{total} cases pass.** Generated by `python evals/run_evals.py`.", "",
             "| Direction | Expected | Category | Pass |", "|---|---|---|---|"]
    for (d, e, cat), (ok, n) in stats.items():
        lines.append(f"| {d} | {e} | {cat} | {ok}/{n} |")
    if failures:
        lines += ["", "## Failures", ""]
        for i, c, got, got_cat in failures:
            lines.append(f"- case {i} ({c['direction']}, expected {c['expect']}/{c['category']}, got {got}/{got_cat}): `{c['text'][:90]}`")
    report = "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "report.md"), "w", encoding="utf-8") as f:
        f.write(report)
    print(report)
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(run("--verbose" in sys.argv))
